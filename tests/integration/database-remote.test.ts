import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { openDatabase } from '../../src/main/core/database';
import {
  DatabaseConnectionRepository,
  DatabaseHistoryRepository,
} from '../../src/main/core/database-repositories';
import { DatabaseWorkbenchService } from '../../src/main/core/database-workbench';
import { WorkspaceRepository } from '../../src/main/core/repositories';
import type { SecretStore } from '../../src/main/core/secrets';
import type { DatabaseConnectionInput, Workspace } from '../../src/shared/contracts';

const enabled = process.env.FORGE_REMOTE_DATABASE_TESTS === '1';
const remoteDescribe = enabled ? describe : describe.skip;
const created: string[] = [];

afterEach(async () => {
  await Promise.all(created.splice(0).map((path) => rm(path, { recursive: true, force: true })));
});

async function fixture() {
  const root = await mkdtemp(join(tmpdir(), 'forge-remote-db-workspace-'));
  const data = await mkdtemp(join(tmpdir(), 'forge-remote-db-data-'));
  created.push(root, data);
  const metadata = openDatabase(join(data, 'forge.db'));
  const workspaces = new WorkspaceRepository(metadata);
  const now = new Date().toISOString();
  const workspace: Workspace = {
    id: crypto.randomUUID(),
    name: 'remote-database-test',
    rootPath: root,
    environment: 'TEST',
    createdAt: now,
    updatedAt: now,
    lastOpenedAt: now,
  };
  workspaces.create(workspace);
  const values = new Map<string, string>();
  const secrets: SecretStore = {
    set: (ref, value) => {
      values.set(ref, value);
      return Promise.resolve();
    },
    get: (ref) => Promise.resolve(values.get(ref) ?? null),
    delete: (ref) => {
      values.delete(ref);
      return Promise.resolve();
    },
    has: (ref) => values.has(ref),
  };
  const service = new DatabaseWorkbenchService(
    workspaces,
    new DatabaseConnectionRepository(metadata),
    new DatabaseHistoryRepository(metadata),
    secrets,
  );
  return { metadata, workspace, service };
}

async function verifyEngine(input: DatabaseConnectionInput) {
  const { metadata, workspace, service } = await fixture();
  try {
    await service.testConnection(workspace.id, input, 'forge-test-password');
    const profile = await service.saveConnection(workspace.id, null, input, 'forge-test-password');
    await service.connect(workspace.id, profile.id);
    await service.query(workspace.id, profile.id, 'DROP TABLE IF EXISTS forge_phase4_people', true);
    await service.query(
      workspace.id,
      profile.id,
      input.engine === 'mysql'
        ? 'CREATE TABLE forge_phase4_people(id INTEGER AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL)'
        : 'CREATE TABLE forge_phase4_people(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL)',
      false,
    );
    await service.mutateRow(
      workspace.id,
      profile.id,
      input.engine === 'postgresql' ? 'public' : input.database,
      'forge_phase4_people',
      { kind: 'insert', values: { name: 'Ada' } },
      false,
    );
    const schema = input.engine === 'postgresql' ? 'public' : input.database;
    const catalog = await service.catalog(workspace.id, profile.id);
    expect(catalog.objects).toContainEqual({
      schema,
      name: 'forge_phase4_people',
      type: 'table',
    });
    const structure = await service.structure(
      workspace.id,
      profile.id,
      schema,
      'forge_phase4_people',
    );
    expect(structure.columns.find((column) => column.name === 'id')?.primaryKey).toBe(true);
    expect(structure.columns.find((column) => column.name === 'id')?.autoIncrement).toBe(true);
    const data = await service.tableData(
      workspace.id,
      profile.id,
      schema,
      'forge_phase4_people',
      0,
      200,
    );
    expect(data.result.rows).toContainEqual([1, 'Ada']);
    const selected = await service.query(
      workspace.id,
      profile.id,
      'SELECT name FROM forge_phase4_people ORDER BY id',
      false,
    );
    expect(selected.rows).toEqual([['Ada']]);
    await service.query(workspace.id, profile.id, 'DROP TABLE forge_phase4_people', true);
  } finally {
    await service.dispose();
    metadata.close();
  }
}

remoteDescribe('remote database adapters', () => {
  it('executes the complete workflow against MySQL 8.4', async () => {
    await verifyEngine({
      name: 'MySQL temporal',
      engine: 'mysql',
      environment: 'TEST',
      host: '127.0.0.1',
      port: Number(process.env.FORGE_MYSQL_PORT ?? 33306),
      database: 'forge_phase4',
      username: 'forge',
      sslMode: 'disabled',
      sqlitePath: '',
    });
  });

  it('executes the complete workflow against PostgreSQL 17', async () => {
    await verifyEngine({
      name: 'PostgreSQL temporal',
      engine: 'postgresql',
      environment: 'TEST',
      host: '127.0.0.1',
      port: Number(process.env.FORGE_POSTGRES_PORT ?? 35432),
      database: 'forge_phase4',
      username: 'forge',
      sslMode: 'disabled',
      sqlitePath: '',
    });
  });
});
